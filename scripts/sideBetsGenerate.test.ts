import { describe, it } from 'vitest';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { PAY_TABLES } from '../src/engine/sideBets/payTables';
import { CUT_FOR_DECKS } from '../src/engine/sideBets/plan';
import type { SideBetRow } from '../src/engine/sideBets/plan';
import { buildSideRow, seedFor } from '../src/engine/sideBets/build';
import type { RuleSet } from '../src/engine/ruleset';

/**
 * Wave L: WRITES src/engine/sideBets/generated.ts. Not a test: skipped unless
 * SIDE_BETS_GENERATE=1, because it simulates a million rounds for every
 * preset pay table at every deck count (several minutes).
 *
 *   SIDE_BETS_GENERATE=1 npx vitest run scripts/sideBetsGenerate.test.ts
 *
 * Deterministic: each row's seed is a hash of its key, so a re-run writes the
 * same file. sideBets.generated.test.ts re-derives what is cheap (edges,
 * effects, tags) and re-simulates a sample row.
 */

const ROUNDS = Number(process.env.SIDE_BETS_ROUNDS ?? 1_000_000);
const DECKS: RuleSet['decks'][] = [1, 2, 6, 8];

export function generateRow(t: (typeof PAY_TABLES)[number], decks: RuleSet['decks'], s17: boolean | null, rounds: number): SideBetRow {
  const key = `${t.bet}/${t.id}/${decks}/${s17 === null ? '-' : s17 ? 's17' : 'h17'}`;
  return buildSideRow({ bet: t.bet, payTable: t.id, decks, s17, cutDecks: CUT_FOR_DECKS[decks]!, rounds, seed: seedFor(key) });
}

describe.skipIf(!process.env.SIDE_BETS_GENERATE)('generate side-bet table', () => {
  it('writes src/engine/sideBets/generated.ts', () => {
    const rows: SideBetRow[] = [];
    for (const t of PAY_TABLES) {
      for (const decks of DECKS) {
        for (const s17 of t.bet === 'buster' ? [true, false] : [null]) {
          const n = t.bet === 'perfectPairs' ? Math.min(ROUNDS, 200_000) : ROUNDS;
          const started = Date.now();
          rows.push(generateRow(t, decks, s17, n));
          console.log(`${t.bet}/${t.id}/${decks}/${s17} ${((Date.now() - started) / 1000).toFixed(1)}s -> ${rows.at(-1)!.chosen}`);
        }
      }
    }
    const out = fileURLToPath(new URL('../src/engine/sideBets/generated.ts', import.meta.url));
    const body = [
      '// GENERATED by scripts/sideBetsGenerate.test.ts -- do not edit by hand.',
      '// SIDE_BETS_GENERATE=1 npx vitest run scripts/sideBetsGenerate.test.ts',
      "import type { SideBetRow } from './plan';",
      '',
      'export const SIDE_BET_ROWS: readonly SideBetRow[] = [',
      ...rows.map((r) => `  ${JSON.stringify(r)},`),
      '];',
      '',
    ].join('\n');
    writeFileSync(out, body);
  }, 3_600_000);
});
