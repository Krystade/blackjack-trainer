import { describe, it, expect } from 'vitest';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { generateAll } from '../src/engine/variants/chartGen';
import { compareAll, upLabel } from '../src/engine/variants/compare';
import { DISAGREEMENT_REASONS, PUBLISHED, SOURCES } from '../src/engine/variants/published';

const JSON_PATH = fileURLToPath(new URL('../src/engine/variants/generated.json', import.meta.url));

/**
 * Wave L: THE variant chart generator, and its drift alarm.
 *
 * The app's Free Bet / Spanish 21 / Switch charts are not typed in anywhere:
 * this test computes them from the EV engine (src/engine/variants/ev.ts via
 * chartGen.ts), compares them with the Wizard of Odds charts transcribed in
 * published.ts, and checks both against the committed generated.json -- which
 * is what the app reads. A change to the engine that moves any cell, house
 * edge or disagreement fails here until the data is regenerated on purpose:
 *
 *   UPDATE_VARIANT_CHARTS=1 npx vitest run scripts/variantCharts.test.ts
 *
 * Same pattern as spokenPhrases.test.ts (the repo has no TS script runner).
 */
function derive() {
  const presets = generateAll();
  const disagreements = compareAll(presets);
  return {
    note:
      'GENERATED by scripts/variantCharts.test.ts from src/engine/variants/ev.ts (infinite deck). Do not edit by hand. ' +
      'disagreements lists every cell that differs from the Wizard of Odds chart, with the reason from published.ts.',
    sources: SOURCES,
    presets,
    disagreements,
  };
}

describe('variant charts', () => {
  const derived = derive();

  it('matches the committed generated.json (regenerate with UPDATE_VARIANT_CHARTS=1)', () => {
    if (process.env.UPDATE_VARIANT_CHARTS === '1') {
      writeFileSync(JSON_PATH, `${JSON.stringify(derived)}\n`, 'utf8');
    }
    const committed = JSON.parse(readFileSync(JSON_PATH, 'utf8')) as unknown;
    expect(JSON.parse(JSON.stringify(derived))).toEqual(committed);
  });

  it('is deterministic: a second run produces the same charts', () => {
    expect(JSON.stringify(generateAll())).toBe(JSON.stringify(derived.presets));
  });

  it('every disagreement with a published chart has a recorded reason', () => {
    const lines = derived.disagreements.map(
      (d) =>
        `${d.preset} ${d.table} ${d.section} ${d.row} v ${upLabel(d.up)}: published ${d.published}, computed ${d.computed}` +
        ` (margin ${d.margin ?? 'n/a'} at ${d.at ?? 'n/a'})`,
    );
    // The full list, for the report and for anyone reading the run.
    console.log(`${lines.length} disagreements:\n${lines.join('\n')}`);
    expect(derived.disagreements.filter((d) => d.reason === null).map((d) => d.key)).toEqual([]);
  });

  it('no recorded reason is stale: each names a cell that still disagrees', () => {
    const live = new Set(derived.disagreements.map((d) => d.key));
    expect(Object.keys(DISAGREEMENT_REASONS).filter((k) => !live.has(k))).toEqual([]);
  });

  it('agrees with the published charts on the overwhelming majority of cells', () => {
    // A cheap guard that the comparison is comparing anything at all: count
    // the compared cells and require them to dwarf the disagreements.
    let compared = 0;
    for (const pub of PUBLISHED) {
      for (const rows of Object.values(pub.sections)) {
        for (const row of rows ?? []) {
          const [range] = row.split(':') as [string];
          const [lo, hi] = range.split('-').map(Number) as [number, number | undefined];
          compared += 10 * ((hi ?? lo) - lo + 1);
        }
      }
    }
    expect(compared).toBeGreaterThan(1500);
    expect(derived.disagreements.length / compared).toBeLessThan(0.05);
  });
});
