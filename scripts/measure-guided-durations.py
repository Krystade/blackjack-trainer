"""Measure every guided-session clip and write src/guided/clipDurations.ts.

The Drive transition's safety cap (GuidedSessionView) is computed from these
real durations rather than a fixed number (review of A9): the first line queues
behind the tap's intro and the command hint, so a fixed cap either cut the
listen beat or waited far too long.

For each sentence guided_sentences() lists (the generator's own mirror of
allGuidedSentences, plus the Drive hint), the LONGEST of the shipped voices is
kept, in milliseconds, so the cap holds whichever voice is chosen.

Needs ffprobe on PATH. Run from the repo root after generating clips:

    python scripts/measure-guided-durations.py
"""
from __future__ import annotations

import importlib.util
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VOICES = ["af_bella", "bf_emma", "bm_george"]
OUT = ROOT / "src" / "guided" / "clipDurations.ts"
NL = "\n"


def load_generator():
    spec = importlib.util.spec_from_file_location("gen", ROOT / "scripts" / "generate-audio-clips.py")
    mod = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(mod)
    return mod


def duration_ms(path: Path) -> int:
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(path)],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    return round(float(out) * 1000)


def main() -> int:
    gen = load_generator()
    sentences = gen.guided_sentences()
    manifests = {
        v: json.loads((ROOT / "public" / "clips" / v / "manifest.json").read_text(encoding="utf-8"))["clips"]
        for v in VOICES
    }
    table: dict[str, int] = {}
    missing: list[str] = []
    for s in sentences:
        longest = 0
        for v in VOICES:
            f = manifests[v].get(s)
            if f is None:
                missing.append(f"{v}: {s}")
                continue
            longest = max(longest, duration_ms(ROOT / "public" / "clips" / v / f))
        if longest:
            table[s] = longest
    if missing:
        print("no clip for:", *missing, sep=NL + "  ", file=sys.stderr)
        return 1
    lines = [
        "// GENERATED by scripts/measure-guided-durations.py -- do not edit by hand.",
        "// Longest duration (ms) of each guided sentence across the shipped voices.",
        "export const GUIDED_CLIP_MS: Readonly<Record<string, number>> = {",
        *(f"  {json.dumps(k)}: {v}," for k, v in sorted(table.items())),
        "};",
        "",
    ]
    OUT.write_text(NL.join(lines), encoding="utf-8", newline="")
    print(f"{len(table)} sentences -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
